/**
 * Regenerates src/lib/geo/zip-county-data.ts from the Census Bureau's 2020
 * ZCTA-to-county relationship file (public domain, US government work):
 *
 *   https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_county20_natl.txt
 *
 *   curl -o /tmp/zcta_county.txt <that URL>
 *   node scripts/generate-zip-county.mjs /tmp/zcta_county.txt
 *
 * For each ZCTA and each state it touches, keeps the county with the most
 * LAND AREA inside that ZCTA (AREALAND_PART) — the Census file has no
 * residential share, so land area is the tiebreak (decided 2026-09-24).
 * States within a ZCTA are ordered by land area, largest first.
 *
 * ZCTAs approximate USPS ZIP codes; PO-box-only and single-business ZIPs
 * have no ZCTA and are not in the output. Rows with no ZCTA (county land
 * outside any ZCTA) and territories outside the 50 states + DC + PR are
 * skipped.
 */
import { readFileSync, writeFileSync } from "node:fs";

const FIPS = {
  "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO", "09": "CT", "10": "DE", "11": "DC",
  "12": "FL", "13": "GA", "15": "HI", "16": "ID", "17": "IL", "18": "IN", "19": "IA", "20": "KS", "21": "KY",
  "22": "LA", "23": "ME", "24": "MD", "25": "MA", "26": "MI", "27": "MN", "28": "MS", "29": "MO", "30": "MT",
  "31": "NE", "32": "NV", "33": "NH", "34": "NJ", "35": "NM", "36": "NY", "37": "NC", "38": "ND", "39": "OH",
  "40": "OK", "41": "OR", "42": "PA", "44": "RI", "45": "SC", "46": "SD", "47": "TN", "48": "TX", "49": "UT",
  "50": "VT", "51": "VA", "53": "WA", "54": "WV", "55": "WI", "56": "WY", "72": "PR",
};

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/generate-zip-county.mjs <tab20_zcta520_county20_natl.txt>");
  process.exit(1);
}

const lines = readFileSync(input, "utf8").replace(/^﻿/, "").split(/\r?\n/);
const header = lines.shift().split("|");
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`column ${name} missing — has the file format changed?`);
  return i;
};
const [iZ, iG, iN, iL] = ["GEOID_ZCTA5_20", "GEOID_COUNTY_20", "NAMELSAD_COUNTY_20", "AREALAND_PART"].map(col);

/** zip -> state -> { land (whole state part), best: [land, county] } */
const zips = new Map();
for (const line of lines) {
  if (!line) continue;
  const r = line.split("|");
  const zip = r[iZ];
  const state = FIPS[r[iG].slice(0, 2)];
  if (!zip || !state) continue;
  const land = Number(r[iL] || 0);
  const county = r[iN];
  if (/[\t\n|:]/.test(county)) throw new Error(`county name would break the encoding: ${county}`);
  if (!zips.has(zip)) zips.set(zip, new Map());
  const states = zips.get(zip);
  const cur = states.get(state) ?? { land: 0, best: null };
  cur.land += land;
  if (!cur.best || land > cur.best[0] || (land === cur.best[0] && county < cur.best[1])) cur.best = [land, county];
  states.set(state, cur);
}

const rows = [...zips.keys()].sort().map((zip) => {
  const states = [...zips.get(zip).entries()].sort((a, b) => b[1].land - a[1].land);
  return `${zip}\t${states.map(([st, v]) => `${st}:${v.best[1]}`).join("|")}`;
});

const out = `// GENERATED by scripts/generate-zip-county.mjs — do not edit by hand.
// Source: US Census Bureau, 2020 ZCTA-to-county relationship file
// (tab20_zcta520_county20_natl.txt), public domain. ${rows.length} ZCTAs.
// One line per ZIP: "ZIP<TAB>ST:County Name|ST:County Name", states ordered
// by land area in that ZIP, each with its largest-land county.
// Server-only: imported by lib/storage-zip.ts, never by a client component.

export const ZIP_COUNTY_SOURCE = "US Census Bureau 2020 ZCTA-to-county relationship file";
export const ZIP_COUNTY_ROWS = ${rows.length};
export const ZIP_COUNTY_TSV = ${JSON.stringify(rows.join("\n"))};
`;
writeFileSync(new URL("../src/lib/geo/zip-county-data.ts", import.meta.url), out);
console.log(`wrote ${rows.length} ZIPs`);
