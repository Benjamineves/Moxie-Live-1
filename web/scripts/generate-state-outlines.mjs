/**
 * Regenerates src/lib/geo/state-outlines.ts — the outlines drawn on
 * /admin/geography, and the projection that places region markers on them.
 *
 * Source: us-atlas v3 states-10m.json (TopoJSON derived from US Census
 * Bureau TIGER/Line, public domain) — the same data the original CA map was
 * made from, by a script that was never committed. This one replaces it for
 * all tracked states, so every outline and every marker uses one method.
 *
 *   curl -o /tmp/states-10m.json https://cdn.jsdelivr.net/npm/us-atlas@3/states-10m.json
 *   node scripts/generate-state-outlines.mjs /tmp/states-10m.json
 *
 * Mercator, fitted to a fixed width with padding; each state's scale and
 * offsets are written out so lib/geo/state-outlines.ts can project a
 * lat/lon marker (lib/region-config.ts) onto exactly the same drawing.
 * Rings smaller than MIN_RING_AREA square units (tiny islets) are dropped
 * and coordinates rounded to 0.1, to keep each path small.
 */
import { readFileSync, writeFileSync } from "node:fs";

const STATES = { CA: "06", FL: "12", WA: "53" };
const WIDTH = 220;
const MAX_HEIGHT = 262;
const PAD = 10;
const MIN_RING_AREA = 2;

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/generate-state-outlines.mjs <states-10m.json>");
  process.exit(1);
}
const topo = JSON.parse(readFileSync(input, "utf8"));
const { scale: [kx, ky], translate: [dx, dy] } = topo.transform;

const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([qx, qy]) => {
    x += qx;
    y += qy;
    return [x * kx + dx, y * ky + dy];
  });
});

function ring(indices) {
  const pts = [];
  for (const i of indices) {
    const a = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    pts.push(...(pts.length ? a.slice(1) : a));
  }
  return pts;
}

const mercator = ([lon, lat]) => {
  const r = Math.PI / 180;
  return [lon * r, Math.log(Math.tan(Math.PI / 4 + (lat * r) / 2))];
};

function area(pts) {
  let s = 0;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) s += (pts[j][0] + pts[i][0]) * (pts[j][1] - pts[i][1]);
  return Math.abs(s / 2);
}

const out = {};
for (const [code, fips] of Object.entries(STATES)) {
  const geom = topo.objects.states.geometries.find((g) => g.id === fips);
  if (!geom) throw new Error(`state ${code} (${fips}) not found`);
  const polys = geom.type === "Polygon" ? [geom.arcs] : geom.arcs;
  const rings = polys.flatMap((poly) => poly.map((r) => ring(r).map(mercator)));

  const xs = rings.flat().map((p) => p[0]);
  const ys = rings.flat().map((p) => p[1]);
  const [minX, maxX, minY, maxY] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
  const scale = Math.min((WIDTH - 2 * PAD) / (maxX - minX), (MAX_HEIGHT - 2 * PAD) / (maxY - minY));
  const height = Math.round((maxY - minY) * scale + 2 * PAD);
  const offsetX = (WIDTH - (maxX - minX) * scale) / 2;

  const project = ([x, y]) => [offsetX + (x - minX) * scale, PAD + (maxY - y) * scale];
  const r1 = (n) => Math.round(n * 10) / 10;
  let kept = 0;
  let dropped = 0;
  const path = rings
    .map((r) => r.map(project))
    .filter((r) => (area(r) >= MIN_RING_AREA ? (kept++, true) : (dropped++, false)))
    .map((r) => `M${r.map(([x, y]) => `${r1(x)},${r1(y)}`).join("L")}Z`)
    .join("");

  out[code] = { width: WIDTH, height, scale, offsetX, pad: PAD, minX, maxY, path };
  console.log(`${code}: ${kept} rings kept, ${dropped} tiny rings dropped, ${WIDTH}x${height}, path ${path.length} chars`);
}

const body = Object.entries(out)
  .map(
    ([code, o]) => `  ${code}: {
    width: ${o.width},
    height: ${o.height},
    projection: { scale: ${o.scale}, offsetX: ${o.offsetX}, pad: ${o.pad}, minX: ${o.minX}, maxY: ${o.maxY} },
    path: ${JSON.stringify(o.path)},
  },`,
  )
  .join("\n");

writeFileSync(
  new URL("../src/lib/geo/state-outlines.ts", import.meta.url),
  `// GENERATED by scripts/generate-state-outlines.mjs — do not edit by hand.
// Source: us-atlas v3 states-10m.json (US Census TIGER/Line, public domain).
// Mercator fitted to ${WIDTH} wide; projectToState() places a lat/lon on the same drawing.

export type StateOutline = {
  width: number;
  height: number;
  projection: { scale: number; offsetX: number; pad: number; minX: number; maxY: number };
  path: string;
};

export const STATE_OUTLINES: Record<"CA" | "FL" | "WA", StateOutline> = {
${body}
};

/** A latitude/longitude as x/y in that state's viewBox. */
export function projectToState(outline: StateOutline, lat: number, lon: number): { x: number; y: number } {
  const r = Math.PI / 180;
  const mx = lon * r;
  const my = Math.log(Math.tan(Math.PI / 4 + (lat * r) / 2));
  const p = outline.projection;
  return { x: p.offsetX + (mx - p.minX) * p.scale, y: p.pad + (p.maxY - my) * p.scale };
}
`,
);
